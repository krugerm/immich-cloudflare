// Writes docs/api-coverage.md: every operation in vendor/immich-openapi.json, ticked when a route exists in src/.
// Usage: node scripts/api-coverage.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const spec = JSON.parse(readFileSync('vendor/immich-openapi.json', 'utf8'));
const norm = (p) => p.replace(/\{[^}]+\}/g, '{}');

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.ts') ? [p] : [];
  });
}

const implemented = new Set();
for (const file of walk('src')) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/\.(get|post|put|delete|patch)\(\s*'([^']+)'/g)) {
    implemented.add(`${m[1].toUpperCase()} ${norm(m[2].replace(/:([A-Za-z]+)/g, '{$1}'))}`);
  }
}

const byTag = new Map();
let total = 0;
let done = 0;
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    if (!['get', 'post', 'put', 'delete', 'patch'].includes(method)) continue;
    total++;
    const key = `${method.toUpperCase()} ${norm(path)}`;
    const has = implemented.has(key);
    if (has) done++;
    const tag = op.tags?.[0] ?? 'Other';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push(`- [${has ? 'x' : ' '}] \`${method.toUpperCase()} ${path}\`${op.deprecated ? ' (deprecated)' : ''}`);
  }
}

const lines = [
  '# Immich API coverage',
  '',
  `Generated by \`node scripts/api-coverage.mjs\` from vendor/immich-openapi.json (${spec.info.version}). ${done} of ${total} operations have a route; a ticked box can still be a stub (see the route module).`,
  '',
];
for (const tag of [...byTag.keys()].sort()) {
  const items = byTag.get(tag);
  const ticked = items.filter((l) => l.startsWith('- [x]')).length;
  lines.push(`## ${tag} (${ticked}/${items.length})`, '', ...items, '');
}
writeFileSync('docs/api-coverage.md', lines.join('\n'));
console.log(`docs/api-coverage.md: ${done}/${total}`);
